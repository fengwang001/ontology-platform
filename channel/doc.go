// Package channel 实现群聊频道的消息序号、编辑/撤回与已读水位服务。
//
// # 模型
//
// 频道由首个 Join 者创建并成为管理员；管理员可 Promote 其他成员。
// 频道参数在创建时固定：编辑时限 E、撤回时限 R（均为 1..86400 秒）、
// 单条消息最多次编辑数 K（0..10）。now 为 [0,10^12] 的整数秒，
// 且不得小于上一次“被接受”操作的 now（被拒绝的操作不推进时钟）。
//
// 序号从 1 开始连续无洞，仅被接受的 Send 占号；撤回不改变序号，
// 消息以“占位”形式保留（序号、撤回者、撤回时刻），正文与提及被清除。
//
// # 并发模型（可线性化）
//
// 所有公开方法在同一把 sync.Mutex 下执行临界区。任何一次调用的整个
// 生效区间都持锁，因此并发历史等价于按某一全局顺序串行执行（可线性化）。
// 查询接口同样取锁以读取一致快照。读水位在锁内校验后只做单调赋值，
// 除“离开后重新加入”这一显式例外外不可能下降。
//
// # 索引结构（复杂度取舍）

// 为使 Unread / UnreadMentions / MarkRead 不随历史消息总数线性增长，
// 采用三组按序号索引的 Fenwick（前缀和树）：
//
//   - aliveBit：未撤回消息计数；Send +1，Recall -1。
//   - authoredBit[u]：u 本人作者的未撤回消息计数；用于从未读中排除自己。
//   - mentionBit[u]：未撤回且“当前”提及集合含 u 的消息计数；
//     Send 按提及人数 +1，Edit 按提及集合对称差增减，Recall 全部 -1。
//
// 于是：
//
//	Unread(u)          = Σ_alive(watermark+1..latest) − Σ_authored[u](同区间)
//	UnreadMentions(u)  = Σ_mention[u](watermark+1..latest)
//	MarkRead(u, upto)  = O(1) 校验后仅写水位（与历史长度无关）
//
// 每次 Send 的循环次数只等于提及人数（≤20），与成员总数、历史长度无关。
// Fenwick 单次加/区间和为 O(log N)。mention/authored 树按用户懒创建。
//
// 提及“按当前集合判定”完全由 mentionBit 的增量维护表达：
// 已读消息被编辑重新提及，其序号不大于水位，区间查询天然不计；
// 编辑删去提及立即 -1；撤回立即 -1 并同时退出未读。
//
// 加入时水位被设为当前最新序号，Fetch 与未读都只看序号大于水位的消息，
// 因此加入（以及离开后重新加入）时刻之前的历史既不可见也不计未读。
//
// # 拒绝次序
//
// 每个操作严格按以下顺序短路返回，只报第一个命中的类别：
//
//	参数非法 > 时钟回退 > 调用者不是成员 > 消息不存在 >
//	权限不足 > 状态（已撤回 > 超时 > 次数超限；水位回退/越界在此层）
//
// 参数（正文、提及集合、seq/limit 取值等）一律先于时钟校验；
// 编辑/撤回的正文与提及合法性属于“参数层”，先于已撤回/超时判定。
// 任何拒绝都在修改状态前返回，因此不改变序号、水位与时钟。
