// Package lineage 实现分片谱系（lineage）与租约消费协调器。
//
// 核心模型：
//   - 键空间为整数 [0,K)，初始仅有一个开放分片覆盖全部。
//   - Append 按键路由到当前唯一覆盖它的开放分片，位置在该分片内从 0 递增。
//   - Split 在 mid（lo<mid<hi）处把开放分片分为 [lo,mid)、[mid,hi)；
//     Merge 要求两个开放分片首尾相接（参数次序无关）。被分裂/合并的分片
//     立即关闭，结束位置 = 已追加条数；子分片位置从 0 起，并记录父分片。
//   - 排空判定：closed && committed == appended；关闭时无记录立即排空。
//
// 租约规则：
//   - 只能授予“未排空、无有效持有者、全部父分片已排空”的分片；
//   - 同一工作者的有效租约数不超过 maxLeasesPerWorker；
//   - 租约自授予/续租时钟起有效 ttl；时钟 >= 到期时刻即失效，他人可接管；
//   - 提交仅接受当前有效持有者，进度只增不减且不超过已追加条数。
//
// 父分片全部排空后子分片才可领取，保证同一键的记录严格按追加顺序被提交消费：
// 键在旧分片上的最后一条记录提交（旧分片排空）之前，承载该键的新分片
// 不可能被任何工作者消费。
//
// 所有方法可并发调用：内部以互斥锁串行化状态读写，分片 ID 由单调计数器
// 分配，同一操作序列的重放结果（成功、错误、返回值）完全一致。
//
// 每次操作都会通过可选的 Logger 打印输入、输出与判定依据。
