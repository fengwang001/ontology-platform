// Package join 实现两表等值连接（Inner / Left），状态全部在进程内存，
// 只依赖标准库。左右两表各是一批行（map[string]any），按一组有序
// 连接键做等值匹配。本文件集中说明语义规则。
//
// # 空键语义（SQL 三值逻辑，不自反）
//
// 某行的任一连接键属性缺失、值为 nil，或值为 float64 的 NaN 时，
// 该行的键视为"空"：Inner 模式下它永远匹配不上任何行——包括另一侧
// 同样缺失该键的行，两个空键不算相等。Left 模式下这样的左行作为
// 未匹配行照常输出。统计上，因键为空而未匹配的左行数
// （Stats.LeftNullKeyRows）与"键有值但右表无对应行"的未匹配数
// （Stats.LeftUnmatchedRows）严格分开。
//
// # 重复键展开
//
// 左表 m 行与右表 n 行落在同一个键上时，Inner 结果恰好产出 m*n 行，
// 每一对只出现一次。Stats.MatchedRows 等于逐键 m*n 之和，
// Stats.MaxKeyExpansion 为所有键上 m*n 的最大值，可用于核对展开总数。
//
// # 输出顺序（完全确定）
//
// 结果与两表的输入顺序、map 迭代顺序均无关：
//  1. 匹配行在前，按连接键逐列升序（类型族序：bool < 数值 < 字符串；
//     数值按大小，字符串按字典序，bool 按 false<true）；
//  2. 同键内按左行标识升序，再按右行标识升序；
//  3. Left 模式的未匹配左行排在最后，按左行标识升序。
//
// 行标识（RowID）由行内容派生，与输入下标无关：属性名升序排列，
// 依次写入 "长度:名字" 与带类型标签的值编码；嵌套 map 递归同样规则，
// 切片按下标顺序。内容完全相同的两行标识相同，但它们产生的结果行
// 也完全相同，因此最终序列仍然唯一确定——任意打乱左右表后重新连接，
// 结果序列逐元素一致。
//
// # 键的比较
//
// 连接键只支持 string、bool、int64、float64 四种类型，其余类型报
// UnsupportedTypeError。同名键在左右两侧（或单侧内部）类型族不一致时
// 返回 TypeError，指出键名与两边类型，而不是判为不等或 panic。
// int64 与 float64 同属数值族，按数值精确相等判断（经 big.Rat 比较，
// 大整数不因浮点转换失真）；+0.0 与 -0.0 相等；NaN 按"空"处理，
// 永不相等并计入 LeftNullKeyRows / RightNullKeyRows。
//
// # 结果行构造
//
//   - 左表属性保持原名；右表的连接键属性不重复出现（以左表为准）；
//   - 右表与左表同名的非连接键属性重命名为 "right." 前缀，仍冲突则
//     继续叠加前缀（如 "right.right.x"），右表绝不覆盖左表；
//   - 右表其余属性保持原名；
//   - Left 模式未匹配行的右侧属性一律"缺失"（键不存在，可用 Has 或
//     comma-ok 辨认），而不是填零值；
//   - 结果行是输入行的深拷贝，双向隔离：改结果不影响输入，改输入
//     不影响结果。
