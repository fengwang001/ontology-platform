// Package join 提供两张表（各为 []map[string]any）之间的等值连接，
// 支持 Inner 与 Left 两种模式。实现只依赖标准库，状态全部在进程内存中。
//
// # 空键语义（SQL 三值逻辑）
//
// 某行的某个连接键属性不存在、值为 nil、或值为 float64 的 NaN 时，
// 该行的该键视为"空"。空键不参与相等比较：在 Inner 模式下该行永远
// 匹配不上任何行（包括另一侧同样缺失该键的行）；在 Left 模式下，
// 这样的左行作为未匹配行照常输出，并计入 Stats.LeftUnmatchedNull，
// 与"键有值但右表无对应行"的 Stats.LeftUnmatchedNoMatch 分开统计。
//
// # 键的类型规则
//
// 连接键只允许 string、bool、int、int64、float64。int 按 int64 处理。
// int64 与 float64 之间可比，按数值相等判断；+0.0 与 -0.0 相等；
// NaN 永不相等（按空键处理）。同一键在左右两侧（或同一侧内部）出现
// 不可比的类型组合时，Join 返回 *KeyTypeError（可用 errors.Is 匹配
// ErrKeyTypeConflict 或 ErrUnsupportedKeyType），错误中指明键名与两侧类型。
//
// # 输出顺序
//
// 结果顺序完全确定，与两表输入顺序及 map 迭代顺序无关：
// 先按连接键逐列升序（数值列按数值、字符串按字典序、bool false 在前）；
// 同键内按 (左行标识, 右行标识) 升序。Left 模式下未匹配的左行排在所有
// 已匹配行之后，按左行标识升序。
//
// # 行标识（Row Identity）
//
// 行标识由行内容派生，与输入顺序无关：把行的属性名排序后，按
// "名字 + 类型标签 + 规范值" 递归拼接（嵌套 map 同样按键排序，切片按
// 下标顺序），得到规范字符串即该行标识。内容相同的行标识相同；
// 内容不同的行标识不同（类型不同也算不同）。
//
// # 结果行构造
//
// 结果行是新分配的 map，与输入行互不影响（键值中的嵌套 map/slice
// 会被深拷贝）。左表属性与连接键保持原名；右表的非连接键属性一律以
// "right." 前缀输出（如右表属性 "x" 输出为 "right.x"），因此右表值
// 永远不会覆盖左表同名属性；若左表本身已含 "right.x"，则继续追加
// 前缀直到不冲突。Left 模式下未匹配的左行不含任何右表属性——调用方
// 用逗号-ok 断言（_, ok := row["right.x"]）即可明确辨认右半侧缺失，
// 而不是看到零值。
