// Package shallow 实现浅克隆仓库的边界管理与对象可达性服务。
//
// 核心概念：
//   - 完整提交图位于远端（Remote），本地只持有其一个前缀截断视图；
//   - 浅边界（boundary）中的提交本地存在，但其父被视为不存在，
//     哪怕这些父恰好也在本地；
//   - 可达性 = 从任一本地引用沿父前进、遇边界停止后经过的提交，
//     以及这些提交直接引用的内容对象；
//   - 深化只能把边界向远端推进，按深度或按时刻两种方式；去浅后边界为空；
//   - 回收删除不可达对象并保持父闭合不变式，回收幂等。
//
// 并发：所有方法可被任意 goroutine 并发调用，语义等价于某个串行顺序。
// 深化、去浅、回收与引用写在同一互斥锁上线性化，可达性查询使用读锁
// 与惰性失效的可达集合缓存。
//
// 错误（按优先级，调用方用 errors.Is 区分）：
//   - ErrInvalidArg    深度非正、引用名为空、时刻为负；
//   - ErrRefNotFound   引用不存在；
//   - ErrRemoteMissing 远端确定不存在该提交；
//   - ErrRemoteFetch   远端不可用或拉取中途失败（整体回滚）；
//   - ErrIllegalState  本地状态非法（引用悬空、边界外提交缺父等）。
//
// 详见 DESIGN.md 与各 *_test.go 中打印输入、输出与判定依据的用例。
