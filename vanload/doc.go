// Package vanload 实现厢式货车的配载与卸货顺序校验系统。
//
// 多个停靠点依次卸货；货物只有在顺序（后卸靠前）、危险品隔离、
// 载重与容积四类约束同时成立时才能放入车厢分区。系统给出确定的
// 装载位置、可区分的失败原因，并在卸货时校验停靠点递增顺序。
//
// 子模块职责：
//   - 领域类型与拒绝原因：cargo.go
//   - 分区聚合状态：state.go
//   - 纯函数约束判定与严重度归并：constraints.go
//   - 线程安全门面（装/卸/查）：system.go
//   - 全有或全无的批量装货：batch.go
//   - 结构化操作日志：log.go
//   - 独立朴素参考模型（仅供测试对照）：naive.go
//
// 设计说明与复杂度证明见同目录 DESIGN.md。
