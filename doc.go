// Package ontology 实现住宅租约到期续签与租金涨幅管制服务。
//
// 核心能力：
//   - 房东在距终止日 [A,B] 天窗口内发出/撤回续签要约；
//   - 租户在 C 天内接受、拒绝或提出一次反要约，房东再答复；
//   - 逾期未决或保护期触发时，租约于终止日后自动按月延续（租金冻结）；
//   - 按月延续期内任一方可通知终止，通知后第 D 天生效；
//   - 按整数金额判定法定涨幅上限（基点档位 + 封顶，不足一分不计）。
//
// 时间模型：租约以整数日序号 [start, end) 表示，所有状态转换只由操作
// 携带的 now 驱动；now 不得小于上一次被接受操作的 now。查询同样反映
// 其 now 下应有的状态，但不推进已提交时钟。错误按固定次序只报告第一个：
// 参数非法、时钟回退、租约不存在、状态不允许、涨幅超限、答复逾期。
//
// 并发：Service 全部方法可并发调用，内部以单锁串行化，结果等价于某个
// 串行顺序（可线性化）。到期判定使用按日排序的事件堆，开销不随租约
// 总数增长；参见 DESIGN.md 与 complexity_test.go。
