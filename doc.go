// Package ontology 提供进程内存中的布隆过滤器实现。
//
// 布隆过滤器是一种空间高效的概率型集合结构：Add 加入元素，
// MayContain 判定元素是否"可能存在"。它保证零假阴性
// （已 Add 的元素一定判定为存在），但允许可控的假阳性
// （未加入的元素有小概率被误判为存在）。
//
// # 参数推导
//
// 给定目标元素数 n 与目标假阳性率 p，位数组长度 m（比特）与
// 哈希个数 k 按经典最优公式推出：
//
//	m = ceil( -n * ln(p) / (ln 2)^2 )
//	k = max(1, round( (m/n) * ln 2 ))
//
// 例如 n=10000、p=0.01 时 m=95851、k=7。构造后可通过 M() 与
// K() 读出实际取值。
//
// # 哈希与确定性
//
// 哈希采用 FNV-1a 64 位的双哈希变体（Kirsch-Mitzenmacher 双重
// 哈希）：先以两个不同的固定偏移基分别算出 h1、h2，第 i 个
// 位置为 (h1 + i*h2) mod m。FNV-1a 完全由输入字节决定，不依赖
// map 迭代顺序，也不使用任何随机种子，因此同一批元素以任意
// 顺序插入，最终位数组逐字节相同；重复插入同一元素是幂等的，
// 位数组不变。
//
// # 元素语义
//
// 元素类型统一为 []byte。nil 与空切片 []byte{} 被视为同一个
// 合法元素（两者哈希输入相同，都是零字节序列）。任意长度的
// 元素（包括百万字节级）都可处理。
//
// # 不支持删除
//
// 本实现刻意不提供 Remove：多个元素共享同一批位，清除某个
// 元素对应的位可能同时清掉其他元素置上的位，从而引入假阴性，
// 破坏布隆过滤器的核心保证。需要删除语义时应改用计数布隆
// 过滤器或布谷鸟过滤器。
//
// # 并发
//
// 所有方法均可并发调用。Add 在写锁下置位，MayContain、Bytes、
// EstimateCount 在读锁下读取：已 Add 完成的元素对后续
// MayContain 立刻可见（无假阴性），Bytes 返回的是某一时刻
// 位数组的完整快照拷贝，不会出现半更新的撕裂状态。
