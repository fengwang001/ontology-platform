// Package join 实现两张内存表（[]map[string]any）在一组有序连接键上的
// 等值连接，仅支持 Inner 与 Left 两种模式。
//
// 本包只做连接这一件事：不涉及存储、索引持久化、查询解析、Link、
// Action 或 HTTP，全部状态仅存在于进程内存，只依赖标准库。
//
// # 空值（三值逻辑）
//
// 连接键上的“空”包括两种情况：
//
//   - 行中不存在该键属性；
//   - 属性存在但值为 nil。
//
// 此外 float64 的 NaN 也按“空”处理（NaN 永不等于自身）。
// 空键不满足自反性：Inner 模式下，两侧同键都为空的两行也不匹配；
// Left 模式下，左行键为空时照常作为未匹配行输出。这两类未匹配在
// Stats 中分别计数：Stats.NullLeftRows（键为空）与
// Stats.UnmatchedLeftRows（键有值但右表无对应行），二者互不重叠。
//
// # 类型判定
//
// 同名连接键两侧动态类型不一致时返回 *TypeConflictError，错误可由
// errors.As 判定，并指出键名与两侧 Go 类型名。例外：int64 与
// float64（以及所有有符号/无符号整数与浮点类型）视为同一“数值”
// 类型族，按数学数值判等；+0.0 与 -0.0 相等。string 与 bool 各为
// 独立类型族，跨族不判为不等，而是报类型冲突。
//
// # 输出顺序
//
// 结果与两表输入顺序、map 迭代顺序均无关，确定性排序规则为：
//
//  1. 按连接键逐列升序（键列顺序即 JoinKeys 的顺序），空键排在最前；
//  2. 同键内按左行标识升序；
//  3. 再按右行标识升序（Left 未匹配行无右侧，视为最小）。
//
// # 行标识
//
// 行不携带任何输入下标，标识 RowID 由行内容派生：先把行编码为
// UTF-8 规范字节串，再取 SHA-256，编码格式见 rowid.go 中的
// encodeRow 注释。因此内容完全相同的两行标识相同；打乱输入顺序
// 不改变任何标识，从而保证结果序列逐元素一致。
//
// # 结果列命名
//
// 结果行只有一个平铺 map[string]any：
//
//   - 连接键保留裸名（如 "k"）；
//   - 其余左表属性加前缀 "left."（如 "left.v"）；
//   - 其余右表属性加前缀 "right."（如 "right.v"）。
//
// 因此左右同名非连接键不会互相覆盖。Left 模式下未匹配的左行，
// 结果行中不写入任何 "right." 键，且 Row.Matched == false，
// 调用方可明确辨认右侧为“缺失”而不是零值。
//
// # 隔离性
//
// Join 在读取输入与构造结果时均做深拷贝，结果行与输入行互不影响。
package join
