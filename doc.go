// Package bloom 提供一个进程内存中的布隆过滤器实现，仅依赖标准库。
//
// # 构造与参数推导
//
// 按目标元素数 n 与目标假阳性率 p 构造（New），内部推出：
//
//	m = ceil( -n * ln(p) / (ln 2)^2 )   位数组长度（比特数），M() 可读
//	k = max(1, round( (m/n) * ln 2 ))   哈希个数，K() 可读
//
// 插入 n 个元素后的理论假阳性率为 (1 - e^(-k*n/m))^k ≈ p。
// 实测值是随机变量，围绕 p 涨落，故验证时采用 [0, 2p] 的宽松上界：
// 足以容纳正常涨落，又能抓住哈希退化等实现错误。
//
// # 确定性与哈希
//
// 哈希采用 FNV-1a 64 位的双重哈希：g_i(e) = (h1 + i*h2) mod m。
// FNV 是纯函数，不依赖 map 迭代顺序，也不含随机种子（因此刻意不用
// hash/maphash，避免其 Seed 带来的不确定性）。同一批元素以任意顺序
// 插入、或同一元素重复插入任意次，最终位数组逐字节相同。
//
// # 语义约定
//
//   - 元素类型统一为 []byte；空切片与 nil 是同一个合法元素。
//   - 空过滤器对任何元素 MayContain 返回假。
//   - 绝不假阴性：Add 完成的元素 MayContain 必为真。
//   - 不支持删除：多个元素共享位，清位会引入假阴性，故不提供 Remove。
//   - Merge 仅在两侧 (m, k) 完全相同时合法，否则返回可判定的
//     ErrParamMismatch（*MismatchError 携带两侧参数）。
//   - EstimateCount 用置位比例反推元素个数：
//     c ≈ -(m/k) * ln(1 - X/m)，X 为已置位比特数。
//
// # 并发
//
// 所有方法并发安全：Add 不丢置位；已完成的 Add 对 MayContain 立刻
// 可见；Bytes 返回某一时刻的完整快照拷贝。
