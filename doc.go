// Package ontology 实现一个分组内 Top-N 选择器。
//
// 行以 map[string]any 流式喂入，按分组键列分组，每组内按分数列取前 N 名。
// 内存上界：任意时刻内部持有的行数不超过 组数 × N，与已处理行数无关。
//
// 组内排序（复合次序，与到达顺序无关）：
//  1. 分数列降序（正负无穷为合法分数）；
//  2. 分数相同，按字符串 tie 列字典序升序；
//  3. 仍相同，按行的内容派生标识升序（见下方定义），不使用到达下标。
//
// 内容派生标识：把行的键按字典序排序，依次拼接 "key\x00value\x00"
// （value 为规范化字符串：字符串原样、布尔用 strconv.FormatBool、整数用
// strconv.FormatInt/FormatUint、浮点用 strconv.FormatFloat 'g' -1、
// nil 为 "<nil>"、其余类型用 fmt.Sprintf("%v")），再取 FNV-1a 64 位
// 哈希的十六进制小写形式。该标识只依赖行内容，与 map 迭代顺序、
// 到达顺序无关。
//
// 分组键：分组列缺失、值为 nil、值为空字符串分别落入三个可辨认的
// 不同的组；其余值（非字符串先以 fmt.Sprintf("%v") 字符串化）各成一组。
// Snapshot 中组的次序：缺失组 < nil 组 < 空字符串组 < 普通组（按键升序）。
//
// 分数列缺失或不是数值的行不参与排名，按组计入 Skipped；分数为 NaN 的
// 行不参与排名，按组单独计入 NaN。
