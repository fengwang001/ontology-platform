// Package ontology 提供多路有序流的集合运算器。
//
// 输入是若干条已按同一比较规则升序排好的 []float64 流，
// 通过一个小顶堆做一次 k 路归并，计算并集、交集、差集。
// 内存占用与流的条数成正比，与流的长度无关。
//
// 相等口径：+0.0 与 -0.0 视为同一个值；NaN 与任何值都不相等
// （包括它自己），因此 NaN 是非法元素，遇到即返回 NaNError；
// 正负无穷是合法元素，正常参与比较。
//
// 有序性校验：每条流必须非递减（相等相邻元素允许），
// 一旦发现严格递减即返回 OrderError，指出流号与下标。
//
// 边界定义：
//   - 零条流的并集：空结果，无错误。
//   - 零条流的交集：数学上有歧义，返回 ErrNoStreams。
//   - 零条流的差集：没有"第一条流"，返回 ErrNoStreams。
//   - 一条流：并集/交集即该流本身（集合语义下去重）；
//     差集即第一条流（集合语义下去重）。
//   - 某条流为空或全部为空：并集为其余流的并；交集为空；
//     差集为第一条流（若第一条为空则结果为空）。
//
// 结果切片均为新分配，输入切片不会被修改。
