// Package ontology 提供进程内存中的分位数查询器。
//
// 支持两种互不串味的口径：
//
//   - NearestRank（最近秩法）：秩 r = ceil(p*N)，结果一定是样本中真实
//     存在的值；
//   - Linear（R-7 线性插值）：小数秩 h = p*(N-1)，在相邻两个样本之间
//     按小数部分线性插值，结果可以不是样本值。
//
// 边界语义：p=0 返回最小值、p=1 返回最大值，两种口径下都是样本中真实
// 存在的值；p 越界或为 NaN 返回 ErrInvalidP；空数据集返回 ErrEmpty。
//
// 权重语义：权重 w 是正整数，等价于该样本重复出现 w 次；实现只保存
// 唯一值及其权重，不做展开，但查询结果与展开后逐位相同。
//
// 浮点语义：+0.0 与 -0.0 合并为 +0.0；NaN 样本被拒绝并计数；正负无穷
// 是合法样本并参与排序。当线性插值落在无穷与有限值之间时，本包选择
// 直接返回该无穷，而不是按算术规则产生 NaN——因为分位点邻域内唯一的
// "真实" 样本就是无穷，返回 NaN 会丢失这一信息。
//
// 查询与样本加入顺序无关，查询不修改内部状态，并发查询安全。
