// Package gc 实现一个带属主引用（owner reference）与终结器（finalizer）的
// 对象级联删除控制器，语义对标 Kubernetes 垃圾回收器：
//
//   - 三种删除策略：后台（Background）、前台（Foreground）、孤立（Orphan）。
//   - 多属主依赖者：依赖者在所有属主都消失后才被连带删除。
//   - 终结器阻塞：终结器非空的对象即使处于删除中也不会被移除。
//   - 前台删除阻塞：前台删除的对象须等待阻塞型存活依赖者消失。
//
// 每个会改变状态的操作在返回前都会把级联收敛到唯一稳定状态；
// 并发调用通过互斥锁串行化，等价于某个串行顺序。
