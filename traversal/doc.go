// Package traversal 在本体图上提供以「路径祖先序列」为判环依据的图遍历服务。
//
// 核心区分：
//
//   - 多路径重复到达（菱形汇聚）：目标对象此前可能经另一条不相交路径到达过，
//     但它不在当前这条路径自己的祖先序列中——这不是错误，照常继续扩展。
//   - 真实环路：目标对象位于当前路径从起点到当前节点的祖先序列中——立即终止
//     沿该方向的扩展，并在 TraversedPath.Cycle 中给出闭合信息与祖先序列。
//
// 判环严格使用每条递归路径独立的祖先集合（进入加入、回溯删除），从不使用
// 任何全局已访问集合，因此菱形不会被误判为环。自环在第一跳即命中；
// 平行链接被展开为互相独立的候选，各自独立判环。
//
// 每条结果路径的终态为 boundary / cycle / depth_limit 三类之一；当同一跳
// 同时满足环路与深度上限条件时，环路判定先执行，固定报告 cycle。
//
// 遍历基于开始时刻原子获取的不可变快照（copy-on-write）执行，
// 遍历期间的并发链接增删不会混入结果。
