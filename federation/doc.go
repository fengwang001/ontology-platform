// Package federation 实现多集群工作负载的副本联邦分配器。
//
// 它把一次分配拆成相互协作的四个部分：
//   - Registry：并发安全的集群动态增删改与一致快照；
//   - allocate：纯函数，执行“最小保障 + 逐轮权重分摊 + 上限饱和再分配”；
//   - buildPlan：由目标与当前承载生成增减量与总迁移量；
//   - AllocError：参数非法 / 配置冲突 / 最小之和超总数 / 容量不足，
//     四类错误有严格优先级。
//
// 所有副本数运算使用 math/big.Int，支持 10^15 乃至更大量级而不溢出；
// 分摊开销只与集群数量有关，与总副本数无关。完整设计与取舍见
// docs/DESIGN.md。
