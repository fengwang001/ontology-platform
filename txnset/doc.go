// Package txnset 解析、合并、求差并规范化输出事务标识集合。
//
// # 用途
//
// 用于复制断点续传场景：把源端已执行事务集合与本地已执行事务集合相减，
// 得到尚待执行的事务集合，并输出任意写法、顺序、重叠输入下唯一的规范文本。
//
// # 文本语法
//
// 文本由逗号分隔的条目组成（空文本表示空集合），不允许任何空白：
//
//	集合    = 条目 *( "," 条目 ) / ""
//	条目    = 来源 ":" 事务号 [ "-" 事务号 ]
//	来源    = ( 字母 / "_" ) *( 字母 / 数字 / "_" )   ; 不超过 MaxSourceLen 字节
//	事务号  = "0" / ( 非零数字 *数字 )                ; int64 范围内
//
// 单个事务号表示单点区间；N-M 表示闭区间 [N,M]，须 N<=M。
// 例如：src-a:1,src-a:2-4,replica_2:10
//
// # 规范化
//
// 同一来源的区间取并集，合并所有重叠或相邻（前一区间 Hi+1 == 下一区间 Lo）
// 的区间；输出时来源按字节序升序、来源内区间按下限升序，单点简写为 N。
// 对任意合法输入反复解析或合并，Canonical 的结果逐字节幂等。
//
// # 差集
//
// Diff 按来源分别做闭区间差集：只对同时出现在两个集合中的来源做减法，
// 来源仅在被减数中出现时原样保留。差集返回新集合，不修改任何输入；
// 被切除内部点后两侧片段不会重新相邻合并（如 [1,5]-{3} = [1,2]∪[4,5]）。
//
// # 错误分类
//
// 解析从左到右扫描并报告第一个错误，整体失败时不并入任何前段条目：
//
//   - KindSyntax（ErrSyntax）：空白、空条目、缺冒号/边界、多余 '-' 等
//   - KindIdentifier（ErrIdentifier）：来源标识字符合法性或长度问题
//   - KindNumber（ErrNumber）：数字非法字符、前导零、int64 溢出、lo>hi
//   - KindTooManyIntervals（ErrTooManyIntervals）：输入条目数超 MaxIntervalCount
//
// 可通过 errors.Is(err, txnset.ErrNumber) 等方式按类别判定。
//
// # 并发
//
// TxnSet 的解析、合并、差集、读取均可并发调用：Merge/MergeText 由互斥锁
// 串行化；Diff 先快照两个操作数再计算，不在持锁状态下嵌套加锁。同一逻辑
// 集合无论如何切分输入、以何种顺序并发合并，Canonical 均逐字节相同。
