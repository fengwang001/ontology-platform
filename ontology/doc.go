// Package ontology 实现本体平台的链接基数约束与批量导入原子性子系统。
//
// 三个协作模块：
//
//   - 基数账本（ledger.go）：按 (链接类型, 侧, 实例) 维护增量计数器，
//     单次校验固定访问两个计数器，开销与链接总数无关。
//   - 批量导入（service.go, batch.go）：按列表顺序逐条应用、批内占用累积；
//     支持全有或全无（失败逆序回滚）与尽力而为（逐条跳过）两种语义。
//   - 错误归一化（errors.go）：参数非法、起点超限、终点超限、链接不存在
//     四类可区分错误，并强制固定判定次序。
//
// 全部变更在单一互斥临界区内串行化，效果等价于某个全局串行顺序；删除对
// 计数的释放与删除本身同时刻生效。设计与本地验证方法见 docs/DESIGN.md。
