// Package ontology 实现本体链接图上的分页邻域遍历器。
//
// 核心能力：

//   - Traverse 从单个起点出发，按链接类型方向做受限 BFS，深度与单节点扇出
//     两个上限独立生效；
//   - 三态截断标记（完整 / 因扇出截断 / 因深度截断），扇出原因优先于深度原因；
//   - 续读标记锚定生成时的不可变快照（MVCC），图变更后续读不漂移、不报错；
//   - 权限（对象存在性、链接遍历权）在扇出计数之前过滤，不可见对象不占名额；
//   - 内部度量 Metrics 只统计本次实际访问的对象与链接，量级为
//     O(fanout^depth) 且与总图规模无关。
//
// 典型用法见同包示例测试与 docs/design.md。
