// Package ontology 提供本体链接图上的权限感知路径查询能力。
//
// 遍历权限由两层声明共同决定：
//   - 对象类型层：权限组对某一整类对象的默认遍历准入（允许 / 拒绝）；
//   - 链接类型层：权限组对某一具体链接类型的遍历准入（允许 / 拒绝 / 未声明）。
//
// 链接类型层声明存在时覆盖对象类型层；两层均未声明时默认拒绝。
// 同一权限主体可属于多个权限组，准入结果由声明所在权限组中优先级数值最高者
// 决定；优先级相同且声明矛盾时按“拒绝优先于允许”合并。
//
// 每次查询在发起时刻对权限状态做一次原子快照，整个查询过程只使用该快照，
// 与并发的声明变更共同满足串行化语义。
