// Package ontology 实现对象类型版本迁移与"运行中实例双写回填"子系统。
//
// 三个协作模块：
//
//   - declaration（声明与兼容性判定）：保存每个属性 keep/add/drop 的当前对应
//     关系、声明修订序号 revision，以及"已经对至少一个已回填实例生效"的
//     冻结集合；自相矛盾、修改冻结对应关系等请求在此被拒绝。
//   - queue（存量实例异步回填）：稳定内部顺序的待回填队列；陈旧项（实例已
//     被写入抢先回填或已删除）保留到出队时由 Store 识别并跳过。
//   - Store（读写路由与一致性仲裁）：一把互斥锁把所有操作全局串行化，
//     负责旧/新读写路由、旧写入等价转换为新写入、即时视图现算、回填仲裁。
//
// 核心一致性约定：
//
//   - 实例未回填时存旧结构 oldRaw，新视图按当前声明逐属性即时投影；
//     旧结构写入先等价转换成新结构写入（补默认值、应用约束），转换完成后
//     实例即视为已回填。
//   - 实例回填后存新结构 newRaw，并记录转换时刻的 Kind 快照；声明之后追加
//     的对应关系不回灌该实例，已生效对应关系随之冻结、禁止修改。
//   - 回填是"一次特殊写入"：出队时实例已回填或已删除都只跳过、不算错误，
//     不覆盖、不复活。
//   - 所有错误先判参数非法（ErrInvalidArgument）再判目标不存在（ErrNotFound），
//     两者可用 errors.Is 区分。
