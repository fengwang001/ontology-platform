// Package blocksched 实现多对端块拉取调度器。
//
// 对一个按 B 个块切分的文件，调度器在若干对端（peer）之间决定每次向谁请求
// 哪一块，规则覆盖最稀有优先、收尾期重复请求、超时降额与校验失败封禁。
// 所有方法持有同一把互斥锁，可被并发调用；任何串行交错都对应一个合法的
// 串行执行顺序。时间 now 单调不减，调用次序相同则最终状态完全相同。
//
// # 选择规则（Next）
//
// 新块阶段：只要存在任何“未完成、全系统当前无在途请求、avail>0”的块，
// 就进入新块选择。候选必须未完成、对端拥有、全系统无在途、该对端对它没有
// 失败记录，按 (avail 升序, 块号升序) 取第一个——即最稀有优先。
// 若存在新块但该对端没有任何可请求的新块，即使它可以重复请求别的块，
// 也返回 (无, false)。
//
// 收尾期：不存在任何新块时才允许重复请求。候选必须未完成、对端拥有、
// 该对端对它没有在途、该块在途数 < M、该对端无失败记录，按
// (该块在途数升序, avail 升序, 块号升序) 取第一个——即在途数优先于稀有度。
//
// avail[b] 是当前未被封禁、未被删除且拥有块 b 的对端数，与块是否完成无关。
//
// # 并发上限
//
// 每对端有效上限 cap = max(1, K - floor(timeouts/2))，timeouts 为该对端
// 累计超时次数；全局在途不得超过 G，同一块在途不得超过 M。cap 因超时下降时
// 已在途的请求允许暂时超出，只限制新的分配。一次成功 Done 会清零该对端
// timeouts，使 cap 恢复。
//
// # 超时与校验失败
//
// Tick(now) 移除所有 now-issued >= T 的在途请求：每条使对应对端 timeouts
// 加 1（cap 随之下降），但不产生失败记录，该块可立即再次被分配。过期项按
// (issued, id, block) 升序返回。
//
// Done(…, ok=false) 移除该请求并给该对端的该块记一条永久失败记录，之后
// 不再向它请求该块；当失败块数达到 F 时封禁：移除其全部在途请求、从所有
// avail 中剔除。封禁记录在 Drop 之后依然保留，同名 id 永远无法再 AddPeer。
// Done(…, ok=true) 标记块完成，取消该块上其余所有在途请求并返回其对端 id
// （升序），同时清零该对端 timeouts。
//
// # 错误优先级
//
//   - Next: ErrClock > ErrNoPeer > ErrBanned
//   - Done: ErrClock > ErrNoPeer > ErrBadArg（块号越界）> ErrNoRequest
//   - AddPeer: ErrBadArg（id 空或 have 长度不对）> ErrPeerExists > ErrBanned
//   - Have: ErrNoPeer > ErrBadArg
//
// 任何返回错误或 (无, false) 的被拒绝调用都不改变状态。
