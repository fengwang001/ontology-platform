// Package room 实现多人对局房间的生命周期服务。
//
// 生命周期为六个顺序阶段：
//
//	等待 waiting -> 倒计时 countdown -> 进行中 playing ->
//	结算中 settling -> 已结束 ended
//
// 任意阶段都可能因规则进入终态“已作废 voided”（空房、在室不足两人、
// 上报争议、上报超时）。已结束与已作废之后所有变更类操作返回
// RejectTerminated。
//
// 时间模型：now 由调用方注入（[0,10^12] 的整数秒）且不得回退。所有
// 到期判断都是惰性的——任何通过参数与时钟检查的操作（含 Snapshot
// 查询）都会先以其 now 处理倒计时/上报期到期，再执行操作本身；开局时刻
// 与超时裁决均以“到期时刻”而不是“操作时刻”为准（恰等于即到期）。
//
// 拒绝原因的优先次序（只返回第一个）：
//
//	invalid_arg > clock_rewind > phase/terminated >
//	not_present > not_owner > conflict
//
// 参数非法或时钟回退的操作不做任何处理；其余被拒操作除时钟推进外不产生
// 任何变化。
//
// 并发：所有方法以单互斥锁串行化，结果等价于某一串行顺序；内部状态
// 不随历史事件数增长，热点操作均为 O(1)（见 DESIGN.md 的性能论证）。
// 独立朴素模型 naiveRoom 与随机差分测试提供可复现的一致性保证。
