// Package payledger 实现支付预授权持有、增量授权与分次捕获的额度账务系统。
//
// # 核心模型
//
//   - 每个卡账户有信用额度与已入账余额；授权在额度内占用一笔持有。
//   - 可用额度 = 信用额度 - 已入账余额 - 全部有效持有。
//   - 金额为正整数最小货币单位，时间为整数天；所有变更操作携带 now，
//     不得小于上一次被接受操作的 now（时钟回退报错），被拒绝的操作
//     不改变任何状态与时钟。
//   - 授权有效期为创建/增量日起 E 天（含第 E 天），过期持有自动失效，
//     不依赖任何操作触发：可用额度是（已接受操作, 查询 now）的纯函数。
//
// # 操作
//
//   - Authorize：唯一编号，占用持有。
//   - Increment：为有效授权追加金额，有效期重置；失败不影响原授权。
//   - Capture：持有转为已入账；超出剩余持有的部分由当前可用额度覆盖；
//     累计捕获不得超过累计授权额按容差基点上浮（向下取整）后的上限；
//     可标记终捕，终捕立即释放剩余持有并终结授权。
//   - Void：释放剩余持有，授权终结。
//   - Refund：只减少已入账余额，不恢复持有，不超过累计已捕获减已退款。
//   - AdjustCredit：调高立即生效；调低不得使可用额度为负。
//
// # 错误优先级
//
// 参数非法 > 时钟回退 > 编号重复 > 授权不存在 > 授权已终结（含过期）
// > 超容差 > 额度不足；退款为 参数非法 > 时钟回退 > 授权不存在 > 超出可退额。
// 每个操作按固定顺序检查，只报告第一个错误。
//
// # 并发与确定性
//
// 所有方法由单一互斥锁串行化，结果等价于某串行顺序；捕获的入账与
// 持有减少在同一临界区内生效，对外不可观察中间态。全部计算为整数
// 运算，无随机、无时间依赖，相同操作序列重放结果完全相同。
//
// # 查询复杂度
//
// 可用额度查询只访问目标账户的 holdTracker（见 hold.go）：前向查询
// 均摊 O(1)，回溯查询 O(log G)（G 为已过期桶数），均不随账户历史
// 授权总数或全部账户数增长。证明见 complexity_test.go 的结构化断言
// 与基准（N 增长两个数量级，查询耗时与分配均保持平坦）。
//
// # 查询语义
//
// 查询是（已接受操作, now）的纯函数：状态与累计额取当前值，仅"是否
// 过期"按查询 now 求值。因此 now 不早于当前时钟的查询给出实时语义
// 下的可用额度（此时非负不变式成立）；早于时钟的回溯查询是确定性的
// 假设求值，可复现但可能混合不同时刻的入账与持有。
