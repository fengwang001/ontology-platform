// Package srcmap 实现源码映射的合成与反查。
//
// 一张映射由若干生成行构成，每行是按生成列严格递增的段序列；段要么指向
// 原始位置（源索引、原始行、原始列），要么是显式未映射段。支持：

//   - New：校验输入并产出唯一规范（最简）形式的不可变映射；
//   - Mapping.Lookup：按位置反查原始位置（二分，亚线性）；
//   - Compose：把“最终→中间”(M2) 与“中间→原始”(M1) 合成为
//     “最终→原始”，在 M1 边界处切开 M2 段（输出敏感的线性时间）；
//   - Service：以名字并发管理映射，保证线性化与错误优先级。
//
// 错误用 MapError 携带 ErrorCategory，分为参数非法、未找到、重复名字、
// 位置溢出四类。设计取舍与复杂度证明见 DESIGN.md。
