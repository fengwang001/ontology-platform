// Package initorder 实现包级变量初始化次序求解会话。
//
// 调用方按源码出现次序逐个登记变量初始化单元（RegisterVars）与函数
// 声明（RegisterFunc），随后通过 Solve 得到唯一确定的初始化次序：
// 反复选取源码次序最靠前且所依赖变量已全部完成的单元，直到全部完成
// 或剩余单元无一可选（初始化环）。
//
// 依赖关系是传递的：直接引用某变量即依赖它；引用某函数即依赖该函数体
// 直接提到的变量，并沿函数间引用继续传递（函数可相互递归）。引用允许
// 前向引用，是否声明在求解时才判定。预声明标识符视为已就绪。
//
// 求解对每个单元给出其传递依赖的变量集合（按名字升序，不含自身变量
// 与空白标识符）作为判定依据。求解不改变会话状态；会话可安全地被
// 多个 goroutine 并发使用，效果等价于所有已接受操作按某个全序串行执行。
//
// 错误分为四类，可用 errors.Is 区分：ErrInvalidArgument（登记参数非法，
// 优先于重复声明）、ErrDuplicateDeclaration（重复声明）、
// ErrUndeclaredReference（存在未声明引用，优先于初始化环）、
// ErrInitializationCycle（初始化环）。
