// Package backupretention 实现“带依赖链保护的分层备份保留管理服务”。
//
// 核心问题：任意给定当前时刻，精确复现“哪些备份必须保留、哪些可以删除、为什么”。
//
// 领域概念
//
//   - 备份分为全量（无父）与增量（必须有已登记父备份），由此形成有根依赖链；
//     子备份创建时刻不得早于父备份（取等合法）。
//   - 保留策略给出日、周、月三层各自的最近周期数量 N（0..1000）。
//     日=UTC 整日；周=周一开始的 UTC 周；月=UTC 公历月。
//     每层在最近 N 个周期（含当前周期，空周期也占名额）各选一个代表：
//     可恢复备份中创建时刻最晚者，时刻相同取标识字典序较大者。
//   - 损坏标记不可撤销：一个备份可恢复，当且仅当它自身与所有祖先都未损坏。
//     只有可恢复备份能当选代表；整周期都不可恢复则该周期无代表。
//   - 依赖保护：直接保留与法律保留的备份，其全部祖先必须保留（祖先是否损坏不限）。
//   - 法律保留不受可恢复性限制，损坏备份也可设置；解除后立即重新按策略判定。
//
// 保留原因彼此正交、可叠加：DirectLayers（日/周/月，可多层）、
// Dependency（仅因后代被保留而保留）、LegalHold（备份自身被法律保留）。
//
// 并发与确定性
//
// 所有方法在单个互斥锁下串行化，等价于某种串行交错；计划是纯函数式计算，
// 相同操作序列重放得到完全相同的计划与保留原因。
//
// 时钟
//
// 一切带时刻的操作（含只读 Plan）要求 now 不小于上一次被接受操作的时刻；
// 被拒绝的操作不改变任何状态，也不推进时钟。
