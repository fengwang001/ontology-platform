// Package reflow 实现渲染树的布局失效与最小子树重排内核。
//
// 五部分相互协作：
//   - 盒树（tree.go）：有序树，每节点维护宽/高模式（Auto/Fixed）、内边距、
//     子节点列表与布局隔离声明；
//   - 脏标记传播（dirty.go）：selfDirty/subDirty 两类标记，沿祖先传播到
//     最近布局边界即止（边界 = 隔离 && 宽固定 && 高固定，根恒为边界）；
//   - 边界判定：见 node.isBoundaryFor；
//   - 重排执行（commit.go）：显式 Commit 只重算各含脏边界最小子树中的
//     受影响节点，子先于父、同父按序，尺寸变化逐跳传播、到边界即止；
//   - 度量查询：Size 在有未提交脏标记时先做与显式提交等价的隐式提交。
//
// 错误由 KernelError 统一返回，ErrorKind 可区分四类，拒绝次序为
// 参数非法 > 节点不存在 > 结构冲突 > 提交中重入。所有公开方法可并发调用，
// 语义等价于某个串行执行顺序。
