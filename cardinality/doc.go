// Package cardinality 实现链接类型某方向基数上限在运行期下调后的
// 级联处理与孤儿清理机制。
//
// 核心概念：
//   - 基数桶 Bucket：由（链接类型, 方向, 源对象）唯一确定，限制该源对象
//     在该方向上可持有的有效链接数量。
//   - 链接状态：active（有效）/ pending（待处理）/ deleted（最终删除）。
//   - 确定性标记依据：同一桶内按 (登记序号 seq, 链接ID) 全序排序，
//     容量之外的链接确定性地落入 pending，重复执行结果一致。
//   - 显式处置 Finalize：pending 链接可被最终删除，或在对象仍有效、
//     容量允许时保留（保留以提升该方向有效上限的方式实现）。
//   - 全序串行化：所有变更操作在引擎内按同一把锁取全局序号，
//     并发交织的结果等价于按该全序串行执行。
