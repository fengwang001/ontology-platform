// Package lifecycle 是本体平台生命周期子系统的状态机模块，
// 负责对象类型的生命周期定义（阶段、允许的转移关系、终态）
// 与对象实例的转移执行。
//
// 它与另外两个模块协作：
//   - hooks：按阶段/转移注册并解析校验钩子的触发范围；
//   - lcerr：把转移拒绝原因归一化为四类可区分的错误。
//
// 转移执行的判定顺序固定为：参数非法 -> 起始阶段为终态 ->
// 转移关系未允许 -> 钩子校验失败，只报告第一个命中的原因；
// 任何拒绝都不会改变实例当前阶段。并发转移按实例互斥锁串行化，
// 效果等价于某个全局串行顺序，阶段历史不会出现分叉。
