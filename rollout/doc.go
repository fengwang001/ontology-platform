// Package rollout 实现带指标闸门与自动回滚的灰度放量流量切分器。
//
// 它把请求在稳定版本（stable）与灰度版本（canary）之间按
// “标识恒定位置 + 阶段比例”切分，随阶段推进逐步放量，
// 并保证同一标识的归属稳定、会话粘性以及“回滚优先”的判定关系
// 可被精确复现。时钟完全由调用方注入（毫秒时间戳），
// 不允许回退；并发调用等价于某个串行顺序。
//
// 核心模型：
//
//   - 位置：Position(id) = FNV-1a(id) mod 10000，范围 [0,10000)。
//     归属灰度当且仅当 Position(id) < 当前比例。
//   - 路由优先级：回滚态强制稳定 > 未过期会话粘性 > 按比例归属。
//   - 评估：驻留满 D、灰度样本不少于 G 后，
//     比较灰度与稳定错误率，阈值为 稳定错误率 + T（万分之一）。
//     全程整数精确比较，无浮点边界误差。
//   - 失败累计达到 F 立即进入已回滚（比例归零、清空全部粘性）；
//     已回滚只能由 Reset 离开。
//   - 粘性用 map + 双向链表（LRU）维护，上限 P；
//     路由与观测的时间复杂度为 O(1)，不随历史请求总数增长。
//
// 错误哨兵与固定优先级：ErrInvalidArgument > ErrClockRewound >
// ErrIllegalState；被拒绝的操作不改变任何状态（含已注入时钟）。
