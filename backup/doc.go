// Package backup 实现带依赖链保护的分层备份保留管理服务。
//
// 服务覆盖：全量/增量备份登记（增量形成依赖链）、日/周/月三层保留
// 代表选取、损坏标记对可恢复性的传递影响、法律保留、过期备份的批量
// 清理。任意时刻都可以通过 PlanCleanup 精确复现“哪些备份必须保留、
// 哪些可以删除、为什么”。
//
// 包内模块划分：
//   - types.go     公共类型：策略、保留原因、错误分类、计划结果。
//   - calendar.go  UTC 日/周（周一起始）/公历月的周期序号计算。
//   - retention.go 保留计划引擎：可恢复性判定、代表选取、保留原因传播。
//   - service.go   服务门面：状态、单调时钟、错误优先级、并发安全。
//
// 所有操作可并发调用，内部以互斥锁串行化，结果等价于某个串行顺序；
// 相同操作序列重放得到完全相同的计划与保留原因。
package backup
