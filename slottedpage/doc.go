// Package slottedpage 实现固定字节大小的槽式（slotted-page）变长记录页。
//
// 页内布局（地址自低向高）：
//
//	+-------------------- 0
//	| 页头 (headerSize)
//	+-------------------- headerSize
//	| 槽目录：每项 slotSize，自前向后增长
//	+-------------------- dirEnd = headerSize + slotCount*slotSize
//	| 连续空闲区（未使用字节恒为零）
//	+-------------------- freeEnd
//	| 记录区：记录紧挨，自页尾向前放置
//	+-------------------- pageSize
//
// 页头前 28 字节为大端元数据：魔数 SPG1(4) | pageSize(4) | headerSize(4) |
// slotSize(4) | slotCount(4) | freeEnd(4) | compactions(4)。
// 槽项前 8 字节为 offset(4) | length(4)；length==0 表示空槽，此时 offset==0。
// 保留字节始终写零，保证同一操作序列产生逐字节确定的映像。
//
// 空间账目：
//
//	可用字节   FreeBytes  = pageSize - headerSize - slotCount*slotSize - 记录字节和
//	连续空闲区 ContigFree = freeEnd - dirEnd
//
// 删除中间记录会在记录区留下空洞（碎片），此时 FreeBytes > ContigFree。
//
// 插入：优先复用编号最小的空槽，无空槽才在目录末尾追加槽项；
// 新记录紧挨当前最低记录（freeEnd）向前放置。连续空闲区足够时绝不整理；
// 连续区不足而全页可用字节足够时，先在整页副本上完成一次整理再放入，
// 整理后编号越小的记录 offset 越大（越靠页尾）且彼此紧挨，槽编号保持不变。
//
// 更新：等长原地覆盖；缩短时向后对齐并清零释放字节；变长增长时若该记录
// 是最低记录且前方连续区足够则原地前移，否则同样在“可用字节足够”时整理、
// 不足时拒绝。删除：仅置空槽；若空槽位于目录末尾，则连同其前方连续空槽
// 一并收回（槽目录收缩）。
//
// 拒绝原因按以下优先级只返回第一个：空记录 -> 单记录带一槽超空页容量 ->
// 编号越界 -> 指向空槽 -> 可用空间不足。被拒绝的操作在所有校验与副本构造
// 完成前不触碰当前页，因而页字节保持不变。
//
// 并发：Page 内部使用 sync.RWMutex；Get/Stats/Marshal 取读锁，
// Insert/Update/Delete 取写锁。整理在独立副本上完成后一次性替换引用，
// 读者永远只能看到整理前或整理后的完整状态。
