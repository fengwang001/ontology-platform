// Package coverage 维护一组可相互重叠的一维半开区间 [lo, hi)，
// 精确回答任意点被多少个区间同时覆盖（覆盖重数）。
//
// 区间绝不合并、绝不去重：同一区间添加三次即产生三层覆盖，Remove
// 一次只减一层，减到零该层才真正消失。
//
// # 端点语义
//
// 区间 [lo, hi) 在 lo 处使覆盖数 +1，在 hi 处使覆盖数 -1。
// 因此 CountAt(lo) 包含该区间，而 CountAt(hi) 不包含。
//
// 同一点 p 同时存在开始与结束事件时，本实现采用“先加后减”的确定性
// 顺序：CountAt(p) 包含在 p 处开始的区间，不包含在 p 处结束的区间。
// 该结果与区间的添加顺序无关，因为半开区间的覆盖函数在点 p 的取值
// 唯一等于“lo <= p 且 hi > p”的区间个数。
//
// # 覆盖总量
//
// 所有区间长度之和可能远超 int64（例如多次添加
// [math.MinInt64, math.MaxInt64)）。本包不存储、不计算该总量：内部只
// 保存各端点的增量（delta）与前缀重数，任何代码路径都不做 hi-lo、
// 中点或宽度计算，因此不会溢出。
//
// # 并发
//
// Counter 由 sync.RWMutex 保护，Add/Remove 与查询可并发调用；
// Segments 返回独立切片，调用方修改它不影响内部状态。
