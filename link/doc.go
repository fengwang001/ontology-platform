// Package link 实现本体平台中两个对象类型之间链接类型的实例层仲裁。
//
// 核心能力：
//
//   - 双方向独立基数上限：每个链接类型在 forward/backward 两个方向分别
//     声明上限，可为 0、正整数或不限（Cardinality）。上限按“有序实例对 +
//     方向”计数：一条 S→T 链接只占用 S 在该方向的名额，与 T 侧反向名额
//     完全独立；对同一有序方向，达到上限后新增请求被拒绝。
//   - 多重链接与去重：同一对实例在同一方向上允许存在多条同类型链接，
//     只要区分属性组合不同。区分属性组合经规范化（canonicalDiscriminator）
//     后比较，完全相同的第二次创建判为 ErrDuplicateLink，不占用名额。
//   - 撤销即释放：删除链接立即从活动集合与度数槽移除。被撤销的区分属性
//     组合可被新链接重新占用；新链接获得全新的 Link.ID，且系统不保留任何
//     已撤销条目的派生状态，因此不存在“继承”。
//   - 并发可串行化：针对同一对实例（不分方向）与相关度数槽的操作在同一
//     临界区内“检查并登记”，消除了 TOCTOU。判定日志在临界区内按提交顺序
//     追加，Seq 即一个保持实时序的合法全序。
//   - 失败分类：创建按固定稳定优先级给出四类互不合并的失败——
//     ErrObjectInstanceDeleted（最高优先）、ErrLinkTypeDirectionNotAllowed
//     （含 ErrUnknownLinkType）、ErrDuplicateLink、ErrCardinalityExceeded。
//   - 失败无副作用：任何被拒请求不写入活动集合、不改动度数；日志是仅追加
//     的审计记录，本身不参与任何判定。
//   - 链接类型隔离：所有集合与度数键均以 LinkTypeID 为命名空间前缀，
//     多链接类型之间基数与判重互不影响。
//
// 查询代价：CountDirection 只读取单个度数槽，为 O(1)；活动集合与度数槽
// 在链接撤销后立即回收，存储规模只与当前有效链接数相关，与历史创建/撤销
// 总量无关（由 TestCountCostIndependentOfHistory 直接断言内部结构规模）。
