// Package inline 实现编译器优化阶段的内联决策子系统。
//
// 子系统拆分为四个协作模块：
//   - graph.go  调用关系登记：函数、调用点、标记的登记与校验，
//     以及决策任务期间拒绝输入修改的并发控制。
//   - budget.go 预算与尺寸核算：每个函数（作为展开根）独立的增长预算
//     与全局绝对尺寸上限，均为硬约束，取等允许。
//   - chain.go  递归判定：直接递归拒绝；互递归按展开链上同一函数的
//     出现次数限流，计数以当前展开路径为准，兄弟分支互不影响。
//   - engine.go + report.go 决策与报告：按热度降序（并列按出现位置、
//     再按调用点标识）考察调用点，输出每个调用点的去向、每个函数的
//     初始/最终尺寸与最深展开链。
//
// 语义要点（保证客观唯一答案的约定）：
//   - 各函数按输入登记顺序依次作为根独立展开；内联时复制被调函数
//     “当前”的函数体：若被调函数已作为根完成决策，则复制其最终尺寸
//     与幸存调用点，否则复制其初始尺寸与原始调用点。
//   - 新产生的调用点与未考察的调用点一起按同一规则重新排序。
//   - 拒绝原因优先级：被调函数未定义 > 禁止内联标记 > 直接递归 >
//     结构不可内联 > 展开链超限 > 预算不足；只报第一个成立的原因。
//   - AlwaysInline 仅豁免预算检查，其余规则（含递归规则）仍然生效；
//     其造成的超预算增长计入调用者尺寸并影响后续判定。
//
// 并发策略：决策任务通过 Registry.Begin 开启会话；会话存活期间对
// 注册表的一切修改请求（Add/Upsert）一律以 ErrBusy 拒绝，会话关闭
// 后的修改对后续会话生效。多个会话可并发进行，互不影响。
