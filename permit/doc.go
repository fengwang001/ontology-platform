// Package permit 实现占道施工许可的时段冲突审查与应急抢修抢占服务。
//
// 能力
//
//   - 受理路段/车道封闭申请（常规 Regular、应急 Emergency），时段一律左闭右开。
//   - 同路段冲突：相交许可封闭车道数之和不得超过路段车道数（恰等于允许）；
//     全封闭与任何相交封闭冲突；首尾相接不算相交。
//   - 绕行冲突（对称、与申请次序无关）：路段全封闭时其指定绕行线上不得有封闭；
//     反之，把本路段纳入绕行线的上游路段全封闭时，本路段不得封闭。
//   - 走廊上限：同一走廊任一时刻并发封闭许可数不得超过配置上限（恰等于允许）。
//   - 应急抢修：只校验参数与应急间同路段车道数，立即抢占相交常规许可；
//     未开始的整体顺延、已开始的截断剩余后顺延，统一挪到应急结束之后，
//     并按原批准次序依次全量重审，先处理者影响后处理者；不通过转待重排。
//   - 延期：延长段按新申请全部规则审查并排除自身原时段；缩短免审查；
//     已开始可延期，已结束不可。
//   - 撤销：未结束许可（含被抢占/待重排）可撤销，撤销后不参与判定，
//     且不会让先前被挡申请自动通过。
//   - 查询任意路段任意时刻的封闭车道数与生效许可；开销不随历史许可总数增长。
//
// 拒绝原因（严格优先，只报最靠前一类）
//
//	参数非法 < 时钟回退 < 路段不存在 < 许可不存在 < 许可已结束 <
//	车道数超限 < 同路段冲突 < 绕行冲突 < 走廊上限 < 起始时刻早于当前。
//
// 所有方法并发安全且等价于某一串行顺序；相同操作序列重放得到完全相同的
// 许可状态历史；被拒绝操作不改变任何状态与时钟。
//
// 朴素全量重判对照模型见子包 naive，设计取舍见 DESIGN.md。
