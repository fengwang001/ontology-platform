// Package bloom 实现一个进程内存中的布隆过滤器。
//
// 构造时给定目标元素数 n 与目标假阳性率 p，由 (n, p) 推出两个参数：
//
//	位数组长度 m = ceil( -n * ln(p) / (ln 2)^2 )        （位）
//	哈希个数   k = round( (m / n) * ln 2 )，且 k >= 1
//
// 这是布隆过滤器的经典最优解：在元素数不超过 n 时，理论假阳性率
//
//	p' = (1 - e^(-k*n/m))^k
//
// 约等于 p。测试中以 [0, 2p] 作为实测假阳性率的宽松上界，理由是：
// 其一，m、k 取整会引入微小偏差；其二，实测值是随机变量，围绕理论值
// 波动，2 倍余量足以吸收统计涨落，同时又紧到能发现实现错误
// （例如哈希分布不均会把实测值推高几个数量级）。
//
// 哈希方案：使用标准库 hash/fnv（FNV-1a 64 位），完全确定，不依赖
// map 迭代顺序，也不使用随机种子（因此无需像 maphash 那样固定 Seed）。
// 由同一元素算出两个 64 位哈希 h1、h2（写入不同的域分离前缀），第 i 个
// 置位位置用双重哈希推出：pos_i = (h1 + i*h2) mod m。
//
// 语义约定：
//   - 元素类型统一为 []byte；nil 与空切片是同一个合法元素（二者哈希相同）。
//   - 空过滤器对任何元素 MayContain 均返回 false。
//   - 不支持删除：多个元素共享置位，清掉任一元素的位可能清掉其他元素
//     赖以判存在的位，从而引入假阴性，破坏布隆过滤器的核心保证。
//     因此本包刻意不提供 Remove。
//   - 并发安全：Add/MayContain/Bytes/Merge/EstimateCount 均可并发调用；
//     Bytes 返回某一时刻的完整快照副本。
