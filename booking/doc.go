// Package booking 实现短租房源的可订日历与预订约束服务。
//
// 职责划分：
//   - types.go    错误码（固定检查次序）、配置、状态与快照类型
//   - treap.go    以起始日为键的区间 treap，带步数计数器，
//     支撑 O(log n) 的邻居查找与复杂度证明
//   - calendar.go 单房源日历：占用索引、按日最短入住、可订性判定
//     （封锁/冲突/间隙/最短入住/孤夜）
//   - service.go  服务门面：时钟单调性、保留的两阶段生命周期与惰性失效、
//     取消退款阶梯、一次性改期、封锁伸缩、并发串行化
//
// 语义要点：预订占用 [入住日, 退房日) 的各夜；now 为整数日且不可回退；
// 保留在创建后 H 个时刻单位内（含最后一刻）可付款；被拒绝的操作不改变
// 日历、预订状态与时钟；所有公开方法可并发调用，等价于某个串行顺序。
