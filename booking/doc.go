// Package booking 实现即时配送的预约单排程系统。
//
// 模块划分：
//   - config.go：构造参数（各提前量、顺延跨度）。
//   - ledger.go：区域/时段名额账本，二分定位与余量判定。
//   - order.go：预约生命周期与“释放=时刻的纯函数”判定。
//   - scheduler.go：下单顺延、原子改期、取消/送达、容量调整、查询，
//     以及用单把互斥锁完成的并发协调。
//   - naive.go：独立编写的全量扫描朴素模型，仅供差分测试对照。
//
// 所有拒绝原因均由 Error.Code 携带（见 errors.go），可程序化区分。
