// Package scheduler 实现一个事件驱动的多路径传输连接发送侧调度器。
//
// 调度器在多个子流之间分配带连接级序号的数据段，区分子流级确认与
// 连接级确认，处理子流失效后的重新注入以及连接级接收窗口约束。
// 所有状态推进均由事件驱动，不依赖时钟。
//
// 基本用法：
//
//	s := scheduler.New(1460)
//	s.AddSubflow("a", 20, 14600, scheduler.Normal)
//	s.ConnAck(0, 65535)          // 通告初始接收窗口
//	d, _ := s.Write(4096)        // d.Sent 为本次发出的段
//	d, _ = s.SubflowAck("a", 1460)
//
// 每个事件处理完后立即进行发送决策并返回本次发出的段。
// 所有方法可并发调用，结果等价于某个串行顺序。
