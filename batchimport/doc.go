// Package batchimport 实现本体平台的批量导入校验钩子可见性子系统。
//
// 子系统由三个职责分离的模块协作完成：
//
//   - runner.go：负责批量导入的分批执行（参数校验、有序调度、提交/撤销、聚合报告）。
//   - view.go：负责钩子触发与批内可见性解析（严格按列表顺序的分层覆盖视图）。
//   - errors.go：负责错误归一化（参数非法 / 前置钩子失败 / 后置钩子失败三类可区分错误）。
//
// registry.go 提供对象类型注册与全局存储，是上述三个模块共享的领域模型基础。
package batchimport
