// Package temporalauth 为本体平台提供面向“时间类属性”的属性级权限校验。
//
// 核心问题
//
// 一次查看请求涉及三种可能不同的时区：属性录入时标注的录入发生地时区、
// 对象所属地区的默认时区（其定义可能随时间版本迁移）、以及查询者所在时区。
// 权限规则允许把“当前是否处于对象所属地区默认时区下的某时间窗口内”作为
// 是否允许查看某时间类属性的条件之一，因此判定前必须把相关时间归一化到
// 同一个基准时区。
//
// 归一化基准（统一、与请求方无关）
//
//   - 判定“当前时刻是否在窗口内”时，窗口边界一律以对象所属地区在判定时刻
//     生效的默认时区版本归一化。
//   - 历史属性取值的归一化基准在“录入那一刻”即被冻结：取录入时刻该地区
//     当时生效的默认时区版本。此后地区再迁移也不改变该记录冻结的结果，
//     因而同一条历史记录在任意请求时刻反复判定都得到一致结论。
//   - 查询者时区仅用于解读查询者提供的本地输入，录入标注时区仅作记录；二者
//     从不作为归一化基准，选取规则对所有请求一致。
//   - 地区默认时区的所有迁移都只能“追加新版本、向后生效”，禁止回溯改写，
//     这是历史结论稳定的前提。
//
// 时间窗口与边界
//
// 窗口以地区默认时区下带日期的民用墙钟时间表述，天然支持跨午夜与跨夏令时
// 切换当天；归一化后统一采用半开区间 [start,end)：Start 归窗内、End 归窗外。
// 夏令时 gap（不存在的本地时间）归一化到跃迁点，overlap（重复本地时间）取
// 偏移更大的更早瞬间，该约定由偏移与跃迁表机械决定，切换当天不设特例。
//
// 错误分类与优先级
//
// 四类错误相互区分，且多类同时成立时只报告优先级最高者：
//
//  1. REGION_TIMEZONE_UNRESOLVED 地区默认时区定义无法确定
//  2. WINDOW_RULE_INVALID         时间窗口规则校验失败
//  3. VIEWER_MISSING              查询者身份/时区缺失
//  4. PROPERTY_DEPRECATED         属性在当前对象类型版本已废弃
//
// 拒绝统一为 DENIED。任何错误或拒绝的对外响应都只携带稳定代码，绝不包含
// 属性归一化取值、所用时区或窗口边界位置；这些细节只写入服务端审计日志。
//
// 并发与复杂度
//
// Store 采用不可变状态 + copy-on-write + 原子指针：写操作在互斥锁内基于
// 当前状态派生新状态并原子发布，读操作以一次原子加载获得 O(1) 一致快照，
// 因而任意并发操作的可观察结果等价于某个全局顺序的串行执行。生效版本解析
// 使用二分查找，单次判定为 O(log n)，并内置探针计数供独立验证。
