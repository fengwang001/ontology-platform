// Package cookie 实现浏览器 Cookie 存储的请求附带判定与按站点容量淘汰内核。
//
// 它由五个相互协作的部分组成：
//
//   - 存储条目：见 [Entry] 与 [WriteInput]。身份键为名字、所属站点、路径、
//     分区键四元组；同键写入是覆盖，保留创建时刻、更新最近访问时刻与其余字段。
//   - 请求上下文判定：见 [RequestInput] 与 [Kernel.Attach]，叠加域名、路径边界、
//     仅安全、未过期、分区键与同站规则，并按路径长度、创建时刻排序。
//   - 同站规则：strict / lax / none 及“未声明按 lax + 可配置宽限”，
//     见 [SameSiteStrict] 等同站常量与 Config.LaxGrace。
//   - 过期处理：expires 恰等于当前时刻即过期；过期条目在被观察到的读取路径上
//     惰性移除并计入过期淘汰，写入时也会先清过期再做容量淘汰。
//   - 容量淘汰：可配置的每站点上限与全局上限，先清过期再按最近访问时刻
//     （并列创建时刻、再按键序）淘汰；全局淘汰优先从条目最多的站点下手。
//
// 三类删除可区分查询：过期淘汰、容量淘汰与显式删除（清除、过期写入）。
// 所有写入、附带、清除与时钟推进均由同一把互斥锁串行化，因此并发结果等价于
// 某个串行顺序，且该顺序中守恒式
//
//	累计新增 == 过期淘汰 + 容量淘汰 + 显式删除 + 当前条目数
//
// 恒成立，可用 [Kernel.Invariant] 校验。判定依据（输入、输出、逐条原因）通过
// [Logger] 打印，默认输出到标准错误。
