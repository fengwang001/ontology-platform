// Package traffic 实现交通事件在路网上的影响传播与排队回溢推演。
//
// 模型概述
//
// 路网为节点与有向路段。每条路段有长度、通行能力 capacity 与恒定到达流量
// arrival（arrival <= capacity）。事件登记在某条路段，带开始时刻与削减比例，
// 使其有效能力降为 capacity*(1-reduction)；同一路段多个同时生效事件取最大削减。
//
// 当 arrival 大于有效能力时按其差额形成排队（以车辆数计，单车占长由配置给出）。
// 排队达到路段容量即“回溢”：该路段的每条直接上游（流入同一节点的边）有效能力
// 被限制为不超过本路段，排队由此只向上游逐级传播；回溢路段的排队保持在容量，
// 直到恢复后净消散把它拉到零，零时刻解除对上游的限制。
//
// 推演是事件驱动且时间可逆切分的：每条路段的排队保存为分段线性锚点
// （anchorTime, q, rate, full），任意时刻 q(t)=q+rate*(t-anchorTime) 并在
// 0/容量处钳制。引擎只在“排队恰好到 0 或容量”以及“事件开始/修改/解除”的
// 精确时刻改变结构，因此一次推进与拆成多次推进逐字段一致。
//
// 有效能力通过对回溢约束做最小不动点松弛求得（环路自然收敛，不重复限制）；
// 受影响等级用多源 BFS 沿回溢边向上游递增，事件路段为一级，多路径取最小。
//
// 所有变更操作携带单调不减的时刻，错误按固定类别次序只报最先的一类；服务对
// 每条公开方法加单一互斥锁，保证并发等价于某种串行顺序，且重放轨迹确定。
// Query 只做一次 map 索引与数组读取，O(1)，不随未受影响路段数量增长。
