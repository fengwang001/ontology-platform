// Package lzw 实现 GIF 风格的变宽码字 LZW 流式编码器与解码器。
//
// 码空间与码宽
//
// 符号为字节 0..255；清除码 256、结束码 257；字典新增条目从 258 起
// 编号，最大 4095。码宽初始 9 位、最大 12 位；码按低位在先
// （little-endian bit order）打包进字节。
//
// 编码规则
//
// 输出的第一个码是清除码（9 位）。维护当前串 w（初始为空）：
//
//   - 读入字节 c；w 为空时 w 直接变为 c（单字节恒在字典）。
//   - 若 w+c 已在字典，w 变为 w+c。
//   - 否则：输出 w 的码；把 w+c 记为新条目 e（取下一个空闲编号）；
//     w 置为 c。
//   - 每次新增后，若 e 恰等于 2 的当前码宽次方且码宽小于 12，则
//     “此后”输出的码宽加一。具体地，条目 512 新增后（下一个空闲
//     编号变为 513）码宽升为 10；条目 1024 后升为 11；条目 2048 后
//     升为 12。
//   - 若 e 等于 4095，则紧接输出清除码（仍用当前码宽 12），字典
//     回到只含 0..257、码宽回到 9，w 保持为 c。
//
// Close 时：若 w 非空先输出 w 的码；随后按正常流程把“下一个空闲
// 编号”计为已占用并做同样的加宽判定（该编号不存在内容、不会被
// 引用）；然后输出结束码；最后用 0 位补齐到整字节。
//
// 例：AAAAAAA 的码序列为 256,65,258,259,65,257，均为 9 位。
//
// 解码端码宽时机的推导
//
// 规则不另行约定，完全由编码规则推出：编码端写出一个“非清除后
// 首码”的数据码 D 时，必同时发生了一次 w+c 不匹配，条目 e 在写码
// 的同一步被占用；因此解码端读取 D 之后、读取下一个码之前，编号
// e 必已占用——即使下一个码是结束码：Close 在最后一个数据码之后
// 仍会补计一个空闲编号，结束码按补计后的码宽输出。
//
// 因此解码端读取“清除后首码之外的任何码”时，一律按
// widthFor(free+1) 取码（free 为当前下一个待新增编号）：
//
//   - 读到数据码：把新条目（上一码对应串 + 本码串首字节；自引用
//     时为本码串首字节，即 KwKwK 情形）回填到编号 free，随后
//     free++。码值等于 free 合法（自引用），大于 free 非法。
//   - 读到结束码：编号 free 只是 Close 的补计，无内容、不回填。
//   - 表满（编号 4095 已建）后读到的必为清除码（12 位），随后
//     复位；其它码按越界拒绝。
//
// 错误处理
//
// 解码按流中先出现者报错，原因可用 errors.Is 区分：
//
//   - ErrNotCleared：首个码不是清除码。
//   - ErrCodeAfterClear：清除码之后的首个码不小于 256。
//   - ErrCodeOutOfRange：码值大于解码端下一个待新增编号。
//   - ErrPaddingNonZero：结束码之后的补齐位非零。
//   - ErrTrailingData：结束码之后还有多余字节。
//   - ErrTruncated：输入在结束码前被 Close 截断（含字节边界处）。
//
// 错误包装为 *CodeError，携带出错码的从 1 起序号（含清除码），
// 可通过 errors.As 取得。解码出错后进入粘滞失败态：后续 Read/Err
// 返回同一原因且不改变状态。编码器 Close 之后再 Write、或重复
// Close 返回 ErrClosed；被拒绝的调用不改变任何状态。
//
// 并发
//
// Encoder 与 Decoder 的方法各自可被多 goroutine 并发调用，内部用
// 互斥锁串行化，结果等价于某个合法的串行调用顺序。编码输出只
// 取决于写入的总字节序列，与 Write 的切分方式无关（逐字节写与
// 一次性写产出逐字节相同的结果）；同一输入重放得到完全相同的
// 码序列与字节流。
