// Package intervaljoin 实现按连接键与闭合事件时间区间配对的双流区间连接器。
//
// 左右两条流各自维护一个只前进的水位线（watermark），侧内事件必须按事件时间 Lo
// 非递减到达（乱序只发生在两条流之间）。对每条到达事件，[Connector.Process]
// 严格按以下顺序处理：
//
//  1. 校验参数（侧合法、事件非 nil、Lo<=Hi、键非空、Lo 不低于本侧水位线、
//     提交并清理后两侧保留数不超过上限）；任一失败即整体拒绝，不留下任何痕迹；
//  2. 用事件的 Lo 更新本侧水位线；
//  3. 与对侧同键的当前保留事件逐一判定区间相交，命中则输出一个 [Pair]；
//  4. 将事件放入本侧保留集合；
//  5. 依据更新后的双侧水位线清理两侧“已不可能再匹配”的事件。
//
// # 匹配条件
//
// 两个事件匹配当且仅当 Key 相等且闭合区间相交：
//
//	aLo <= bHi && bLo <= aHi
//
// 区间两端均闭合，因此端点相等也算命中：[1,10] 与 [10,20] 配对，
// [1,10] 与 [11,20] 不配对。每个左侧事件与每个右侧事件至多配对一次
// （后到的一方扫描先到一方的保留集合）。
//
// # 清理规则
//
// 对侧未来事件的 Lo 不会低于对侧当前水位线 wm，所以一条区间为 [Lo,Hi] 的事件，
// 当且仅当 Hi < wm 时才不可能再与对侧任何未来事件相交，应被删除；
// Hi == wm 时仍可能与下一条 Lo==wm 的事件在端点相交，必须保留。
// 对侧水位线尚未建立时不清理该侧。清理在每一步提交后对两侧各执行一次。
//
// # 拒绝原因
//
// 被拒绝的操作返回 [*JoinError]，用 [errors.As] 取出后按 Code 区分：
// [CodeInvalidParameter]、[CodeEmptyKey]、[CodeTimeRegression]、
// [CodeRetentionLimitExceeded]。拒绝是原子的：水位线、本侧编号序列、
// 两侧保留状态与已输出配对均不变。
//
// # 并发与确定性
//
// Connector 用单一 RWMutex 串行化写入；[Connector.Pairs]、[Connector.Retained]、
// [Connector.Watermark] 在读锁下返回深拷贝快照，并发只读得到逐字段一致的结果。
// 输出顺序只依赖输入序列（同一步内按对侧编号升序），同一序列反复计算结果完全相同。
//
// 通过 [SetLogger] 可重定向日志；日志逐行打印输入（侧、编号、键、区间、水位线
// 变化）、每次匹配的两个子判定及其布尔结果、每条事件的清理/保留依据、每步输出，
// 以及每次拒绝的原因码与细节（reject 行）。
