// Package intervaljoin 实现一个双流区间连接器（interval join）。
//
// 左右两条事件流各自携带连接键 Key 与一个两端闭合的事件时间区间 [Lo, Hi]，
// 连接器在“同一连接键 + 区间相交”的条件下把左右事件两两配对，保证在乱序
// （仅本侧内部有序）、清理与边界场景下既不漏对也不多对。
//
// # 到达顺序与水位线
//
// 两条流相互独立，各自维护单调非递减的水位线：事件 e 到达侧 S 时，S 侧
// 水位线推进为 max(原水位线, e.Lo)（实现即赋值 e.Lo，因为倒退会被拒绝）。
// 两侧内部必须按 Lo 非递减到达；一条 Lo 小于本侧水位线的事件以
// CodeTimeRegression 整体拒绝，不改变任何状态。
//
// # 匹配条件（两端闭合）
//
// 事件到达时只与“对侧当前保留的、同键”事件比较。两个闭合区间相交当且仅当
//
//	a.Lo <= b.Hi 且 b.Lo <= a.Hi
//
// 因而端点相切也算匹配：[0,10] 与 [10,20] 在 t=10 配对，点区间 [10,10]
// 同样参与端点匹配。不同连接键的事件永不配对。每个左右事件对只输出一次
// （后到者与先到者配对），累计结果可经 Pairs 读取。
//
// # 清理规则（每步精确）
//
// 完成本步配对后，用更新后的双侧水位线清理两侧。对侧未来事件的 Lo 不会
// 低于其水位线 W，因此本侧一个事件 [Lo,Hi] 已不可能再匹配，当且仅当
//
//	Hi < W   （严格小于）
//
// 等号必须保留：Hi == W 时仍可能与下一条 Lo==W 的对侧事件在端点上闭合
// 相交。若对侧水位线尚未初始化（对侧还没有任何事件到达），则一侧都不清。
//
// # 拒绝与原子性
//
// 下列情况返回 *JoinError（用 errors.As 取 Code 区分原因），且被拒绝的操作
// 不改变水位线、事件编号、两侧保留集合或已输出配对：
//
//   - CodeInvalidParameter：配置非法（MaxRetainedPerSide<=0）、事件为 nil、
//     Lo>Hi、Side 非法；
//   - CodeEmptyKey：连接键为空串；
//   - CodeTimeRegression：事件 Lo 小于本侧水位线；
//   - CodeRetentionLimitExceeded：处理完这一步（含清理）后某侧保留事件数
//     超过 Config.MaxRetainedPerSide。
//
// 上限按“这一步提交并清理之后”的保留数量判定：提交前先预演，超限则整步
// 不落状态（编号也不消耗）。
//
// # 并发与确定性
//
// Process 使用写锁串行化；Pairs、Retained、Watermark 使用读锁并返回深拷贝，
// 并发只读得到逐字段一致的快照。匹配输出按对侧事件编号升序，Pairs 返回按
// (LeftID, RightID) 排序的累计结果；同一输入序列反复计算输出完全相同。
//
// 日志（SetLogger 可重定向，默认 stderr）逐条打印输入、每个候选对的相交
// 判定依据、每条事件的保留/清理依据，以及每步输出的配对数。
