/*
Package delay 设计说明（航班延误连锁调整引擎）

1. 模块划分：model.go 放类型/配置/错误与内部结论结构；engine.go 负责
   校验、建链、互斥、时钟、注入/撤回与拒绝次序；sweep.go 是唯一的
   推算内核；naive.go 是独立编写的整表朴素对照模型；两个 *_test.go
   覆盖边界与随机对照。
2. 结论唯一不动点：全部规则按“计划起飞时刻（同分按输入序）”单向扫描
   即可确定，飞机链与机组链都是该序的子序列，故无需迭代即得唯一解。
3. 取消根 croot 携带 (time, reasonRank, birth)：注入锚定 -1，宵禁/值勤
   锚定其到达时刻；多原因同时成立时按该三元组取最早，与注入次序无关。
4. 取消转移：飞机/机组各持滚动态（所在机场、滞留根、ready 下界、
   机组 dead 与首个实际起飞段）；取消段只让“能到达起飞机场”的资源
   停留，不到场资源保留原机场与根，链上传导到机场匹配处停止。
5. 值勤：dead 为永久标记，仅在资源可用并算出时刻后判定，跨度恰等于
   DutyLimit 允许；该段及机组链后续取消，但不污染飞机侧滞留根。
6. 宵禁：Contains 严格左闭右开；起飞落入推迟到区间末，到达落入取消。
7. 增量：一次注入只把种子沿两条链向下游 BFS 出受影响集合（遇已起飞
   冻结段停止），扫描仅处理该集合；前驱结论已含全部历史，故每段状态
   用直接前驱结论 O(1) 重建。Get 为 map 直取，O(1)。
8. 被放弃方案：按依赖图迭代到不动点（实现复杂、难证唯一）；只存当前
   滞留根不存机场（撤回后无法正确恢复 ready 下界）。两者均被放弃。
9. 并发：单把 sync.Mutex 串行化所有写操作，天然等价于某串行顺序；
   扫描顺序与平手键均确定，重放逐航班一致。
10. 本地验证：GOCACHE=/tmp/gocache go test -race -v ./delay/
    定向用例见 engine_test.go，1500+ 组随机/300 组冻结与朴素模型
    逐航班对照、TestIncrementalCost 用 LastSwept 计数证明重算规模
    不随总航班数增长；-v 日志打印每步输入、输出与判定依据。
*/
package delay
