// Package subtype 实现支持递归命名类型的结构化子类型判定。
//
// 模块划分：
//   - types.go    类型表达式（基本类型、顶/底、对象、函数、联合、引用）及其规范化
//   - errors.go   可区分的错误类别（参数非法/重复定义/未定义引用/无保护循环）
//   - validate.go 结构校验、静态可达闭包、无保护循环检测
//   - engine.go   子类型判定引擎：有限对集合上的最大不动点
//   - registry.go 并发安全的登记与判定入口，定义快照与错误优先级
//
// 子类型关系取满足全部结构规则的最大解（共归纳语义）：
// 判定中遇到尚未得出结论的同一对类型视为成立。引擎通过在
// V(S) × V(T) 的有限子集上从顶元素迭代单调算子直到稳定来计算该最大解，
// 因此一次判定考察的不同命名对数量不超过两侧可达命名类型数量的乘积。
