// Package replication 实现基于领导者世代（generation/term）的跟随者日志截断。
//
// 核心问题：领导者更替后，旧领导者可能已经向部分跟随者复制了分叉条目。
// 新领导者恢复跟随者时，只需把跟随者日志尾部的分叉部分截掉，使其成为
// 领导者日志的前缀；后续正常复制负责把它追平（恢复过程只截断、不拉取）。
//
// # 世代缓存
//
// 每个副本维护有序缓存 []GenMark{Gen, Start}，表示世代 Gen 的第一条消息的
// 起始位点。追加缓存项的时机：
//   - BecomeLeader 当选新领导者时，在当前日志末尾登记新世代；
//   - Append / Replicate 收到更高世代的消息时，在该消息位点自动登记；
//   - 世代号必须严格递增；世代起始位点必须落在当时的日志末尾。
//
// 截断 truncateAt(pos) 删除位点 pos 及之后的日志，并删除所有 Start >= pos
// 的缓存项（包括空世代标记），保证缓存始终与剩余日志一致。
//
// # 领导者响应
//
// GenerationEnd(leader, gen, start) 按请求世代（含跟随者记录的起始位点）
// 返回该世代日志的独占结束位点。世代号不存在、或同号世代起始位点不一致
// （同号不同分叉分支）均返回 ErrUnknownGeneration。
//
// # 恢复规则
//
// RecoverFollower 每轮取跟随者缓存中最新的世代：
//  1. 领导者没有该世代（或起始位点不一致）：删除该世代缓存项并截到其
//     Start——只删除确定分叉的部分；
//  2. 领导者有该世代：在 [Start, GenerationEnd) 内逐位点比较，第一条分歧
//     即截断点；跟随者比领导者长时，截到领导者的结束位点；
//  3. 世代区间完全一致且无多余尾部时结束。返回值即最长公共前缀长度。
//
// 多轮执行保证最终截断点与朴素逐位点 LCP 一致；恢复后调用 Replicate 必然
// 成功，再次 RecoverFollower 为幂等空操作。
//
// # 并发与失败原子性
//
// 世代响应、日志查询等只读调用可并发执行到不同副本；多副本操作按副本名
// 排序加锁以防死锁，单次恢复自始至终持有领导者与跟随者的锁。所有写操作
// 先完整校验、再变更；任何参数/副本/世代/分叉拒绝都不会改动任何副本的
// 日志或世代缓存。
