// Package gengc 实现一个语言运行时的分代垃圾回收模型。
//
// 托管对象空间分为年轻区与年老区：对象在年轻区分配，存活并熬过
// Config.PromoteThreshold 次年轻区回收后在该次回收中晋升到年老区。
//
// 年轻区回收只扫描年轻区：起点是“根直接引用的年轻对象”与“记忆集中
// 年老对象所引用的年轻对象”，随后仅在年轻对象之间传播。记忆集由写屏障
// 维护——只有“把指向年轻对象的引用写入年老对象字段”才登记该年老对象，
// 登记粒度为对象而非字段，同对象多次写入只算一次。每次年轻区回收结束时
// 记忆集被重算（旧成员 ∪ 本次晋升者中仍引用存活年轻对象者）。
//
// 年老区回收只能由 CollectOld 显式触发，它扫描整个托管空间、从根判定
// 可达性、清除死亡年老对象及相应记忆集项，且不改变任何对象的回收次数。
//
// 所有方法在单个互斥锁下串行化，因此并发的分配、读写与回收严格等价于
// 某个全局串行顺序；字段写入与屏障登记在同一临界区内完成。
//
// 操作拒绝次序固定为：未定义引用 > 参数错误 > 悬垂引用 > 空间不足；
// 被拒绝的操作不改变对象、记忆集、根集合与统计。
