// Package replica 维护单个分区的同步副本集（ISR）与高水位（HWM）。
//
// 模型
//
// 每个副本有一个日志结束位点 end（已拥有日志 [0, end)）与一个“追上时间”
// caughtUpAt（最近一次与领导者位点齐平的时间）。同步副本集 synced 始终
// 包含领导者。高水位 hwm 是已提交位点：
//
//	hwm = min{ 同步副本集内每个副本（含领导者）的 end }
//
// 高水位只进不退：任何一次重算得到的值若小于当前 hwm 将触发不变量断言
// （正常输入下不可能发生）。
//
// 操作
//
//   - NewSyncSet：建立分区，领导者以位点 0、hwm=0 起步并位于同步副本集。
//   - AddReplica：注册跟随者，初始位点 0、不在同步副本集。
//   - Append：仅领导者调用，写入 n 条日志推进领导者 end；随后重算 hwm。
//   - Fetch：跟随者拉取后回报已拥有位点。位点单调、不得超过领导者；
//     当 end 与领导者位点齐平时刷新 caughtUpAt；当被移出（或新注册）的
//     副本追到 end == 领导者位点（必然 >= 当前 hwm）时重新加入同步副本集。
//   - Sweep：周期性检查。caughtUpAt 距 now 的落后时长“严格大于”
//     tolerance 时把跟随者移出同步副本集（恰好相等保留；领导者永不移出）。
//     移出后按新的同步副本集重算 hwm，数值只会被顶住或前进。
//   - Status：返回领导者、hwm、同步副本集（注册顺序）与全部副本位点。
//
// 边界与错误类别
//
// 所有参数错误都返回可比较、互不相同的哨兵错误，且整体拒绝——在校验全部
// 通过前不写入任何状态，因此被拒操作不会留下痕迹：
//
//   - ErrInvalidArgument：空副本名、重复注册、负写入长度、位点溢出、
//     零值时间、负容忍时长、跟随者以领导者身份拉取等。
//   - ErrUnknownReplica：Fetch 引用未注册副本。
//   - ErrInvalidOffset：负位点、超过领导者位点、相对自身已报告位点回退。
//   - ErrClockRollback：操作时间早于系统已观察到的最新时间。
//
// 时间必须由调用方显式传入且全局单调（Append/Fetch/Sweep 共用一个逻辑
// 时钟），这让行为完全确定、可复现，也便于测试时钟回退拒绝。
//
// 并发
//
// 全部方法可被多个执行体并发调用；内部以 RWMutex 串行化写操作，
// 每次操作对“校验 + 状态变更 + hwm 重算”原子生效。
//
// 日志
//
// 通过 WithLogWriter 可将逐步输入、同步副本集与判定依据写入指定 io.Writer
// （默认 os.Stderr，nil 表示丢弃）。
