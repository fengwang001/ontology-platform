// Package callstack 实现小型函数式语言运行时的调用栈管理：
// 纯语法尾位置判定、尾调用帧复用、调用回溯、深度/配额上限、
// 异常传播与一致的并发统计读取。
//
// 模块：tailpos.go（AST 与尾位置；载入期一次标注，运行时读布尔字段，
// O(1) 且与函数体大小无关）；frame.go（帧、槽位、入栈/弹出/尾复用、
// 配额与回溯快照；不带锁；回溯只随物理帧、不随省略帧增长）；
// instance.go（解释器、调用事务、异常、统计、日志）；parser.go
// （S 表达式、槽位静态分配、尾标注）；errors.go（六类可区分错误）。
//
// 取舍：尾调用走 trampoline 循环、不新增物理帧，非尾调用才递归。
// 拒绝调用的检查（已关闭→未定义→参数→深度→配额）在单个写临界区、
// 且先于任何修改完成；尾复用先预检“释放旧帧+占用新帧”净额，失败不落盘，
// 原帧完好。折叠计数存于物理帧：尾复用 +1，非尾新帧归 0。入口帧
// <main> 永不复用，回溯恒有根。异常以 panic/恢复沿非尾帧逐帧弹出，
// 被尾替换的帧不在传播路径、其保护区域随之失效。读取走 RLock 整体
// 拷贝快照，等价于把读插入某次调用边界。
//
// 放弃：setjmp/异常表（词法区域用 defer+恢复更直接，且天然表达尾替换
// 后旧区域失效）；回溯时重放省略帧（会使成本依赖折叠数）。
//
// 验证：GOCACHE=/tmp/gocache go vet ./callstack；
// GOCACHE=/tmp/gocache go test -race -v ./callstack；
// GOCACHE=/tmp/gocache go test ./callstack -bench . -run '^$'。
// 覆盖尾位置形态/反例（含保护区域末尾）、深度/配额取等、事务回滚、
// 折叠累加归零、异常跨省略帧、300 组随机链对朴素模型、多实例与
// 并发读一致性、两条 O(1) 基准；BufferLogger 打印输入/输出/依据。
