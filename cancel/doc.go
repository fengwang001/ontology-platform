// Package cancel 实现即时配送订单的取消责任判定与退款分摊。
//
// 模块划分：
//   - errors.go / types.go：可程序化区分的错误码、阶段、责任方与金额类型；
//   - adjudicate.go：依据阶段、发起方、时刻与争议声明裁决责任方（纯函数）；
//   - split.go：退款在现金/优惠券间的拆分与四方账目（纯函数，保证守恒）；
//   - dispute.go：争议窗口状态与全局到期最小堆（惰性失效）；
//   - service.go：时钟、状态机、统一拒绝次序与并发协调（单锁线性化）。
//
// 时刻为整数秒且全局单调；被拒绝操作不改变时钟、阶段与账目。
// 金额为非负整数分。任何落地取消都满足：
//
//	UserRefund + Merchant + Rider + Platform == 用户实付 + 优惠券面额
