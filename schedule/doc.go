// Package schedule 实现“按月第 N 个星期几”重复的日程系列管理器，
// 支持实例展开、取消、改期单个实例，以及“此次及以后”拆分系列。
//
// # 日期与星期
//
// 日期统一为公历 "YYYY-MM-DD"，年份限 1970..2200；
// 格式错误、不存在的日期（如 2025-02-29、2 月 30 日）一律拒绝。
// 星期按 ISO 编号：周一 1 … 周日 7。
//
// # 系列
//
// 系列由 (id, start, rule, termination) 组成：
//   - rule: 间隔月数 k（>=1）、序号 nth（1..5 或 -1 表示当月最后一个）、星期 w（1..7）；
//   - termination: 总实例数 count（>=1）与截止日 until（含当日）二者恰给一个。
//
// # 候选生成
//
// start 所在月为第 0 个月，之后每隔 k 个月（即相对 start 的月份偏移为
// 0, k, 2k, …）取该月第 nth 个星期 w 作为候选：
//   - 早于 start 的候选不是实例（例如 start 晚于同月第 nth 个星期 w 时），
//     不顺延到下一月；
//   - 某月不存在第 5 个星期 w（nth=5 时）则该月整体跳过：不顺延、不占名额；
//   - 候选日期晚于 2200-12-31 时不再生成；
//   - count 与 until 都按“原日期”（规则生成的日期）计数，与改期后的实际日期无关；
//   - until 型在第一个晚于 until 的候选处终止。
//
// # 名额归属与例外
//
// count 统计的是规则生成的所有实例，被取消或被改期的实例同样占名额，
// 不会因取消/改期而顺延补出新实例。取消与改期是挂在“实例原日期”上的例外：
//   - 取消：实例不再出现在展开结果中；对已改期实例取消会同时释放其改期日；
//     重复取消被拒绝（INSTANCE_ALREADY_CANCELLED）。
//   - 改期：实例移动到新的实际日期，新日期不必满足规则；对已改期实例再改期
//     只移动到更新日期并释放旧改期日；改期目标被同系列另一实例
//     （原位或改期而来，已取消的除外）占用时拒绝（TARGET_DATE_OCCUPIED）；
//     对已取消实例改期按“取消已被取消的实例”同一原因拒绝。
//
// # “此次及以后”拆分
//
// Split 的 date 必须是原系列某个实例原日期（含已取消/已改期者）；
// “date 之前 / date 及之后”一律按实例原日期判断。
//   - 原系列只保留 date 之前的实例：count 型把 count 改为 date 之前的实例数
//     （可以为 0，系列仍保留但无实例）；until 型把 until 改为 date 前一天
//     （date 之前为 0 时 until 可早于 start）。
//   - 原系列例外中属于 date 及之后实例的取消与改期全部丢弃。
//   - 新系列用新 id、新规则，start=date；其第一个候选是“不早于 date 的首个
//     符合新规则的日期”（新规则同月候选早于 date 时跳过该月）。
//   - 新系列剩余名额：原 count 型为 原 count 减 date 之前实例数；
//     原 until 型沿用原 until。
//
// # 展开
//
// Expand(from,to) 返回所有系列在半开区间 [from,to) 内的实例
// （系列 id、原日期、实际日期）：取消的不出现；改期的按“实际日期”判断是否
// 落入区间；结果按 (实际日期, 系列 id, 原日期) 升序。
// 区间为空（from>=to）或跨度超过 3660 天会被拒绝。
//
// # 并发与可复现
//
// 所有方法可并发调用：写操作在互斥锁内原子完成，被拒绝的操作不改变任何状态；
// 展开在读锁内深拷贝系列集合，因此看到的是某一时刻的完整快照，
// 整体等价于某个串行顺序。操作与结果本身是纯确定性的，
// 相同操作序列重放得到完全相同的展开结果（见 TestReplayDeterminism）。
//
// # 本地验证
//
//	cd <repo>
//	go test ./schedule/                       # 含 200 组与朴素逐日扫描实现的差分对照
//	go test -race -count=1 ./schedule/        # 竞态检测
//	go test -run TestFifthWeekdayMissingSkipped -v ./schedule/
//	go vet ./...

