// Package reconcile 提供本体平台多副本快照的对账与和解能力。
//
// 各副本节点独立产出快照，快照对应的逻辑位点可能互不相同。
// 本组件将一组副本快照归并为一份唯一确定的和解结果：
//
//   - 位点基准：和解结果对应所有可读副本中最早的逻辑位点，
//     晚于该位点才写入的内容一律不计入。
//   - 冲突裁决：同一位点上同一对象实例的同一属性出现不同取值时，
//     按副本自身携带的可比较标识（Priority）裁决，优先级高者胜出；
//     裁决结果与副本数量、到达顺序无关。
//   - 损坏隔离：结构性损坏（整体或局部）的副本不参与内容裁决，
//     但不影响其余副本之间的和解。
//   - 不可和解：最高优先级上出现并列的不同取值时，该对象实例
//     被判定为不可和解，不退回按到达顺序强行裁决。
//
// 组件按职责划分为四个协作部分：损坏隔离（quarantine.go）、
// 位点基准确定（baseline.go）、冲突裁决（adjudicator.go）、
// 编排与报告（reconciler.go）。
