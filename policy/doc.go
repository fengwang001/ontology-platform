// Package policy 实现长期寿险保单的保费宽限、自动垫交、中止与复效状态引擎。
//
// 模块划分：
//   - types.go：状态、判定结论、配置、快照与可区分错误；
//   - loan.go：借款账，聚合计账，O(1) 计息、还款与结清；
//   - policy.go：单保单状态机与事件结算（应缴、宽限期满、垫交、中止、终止）；
//   - engine.go：并发安全的引擎入口，固定拒绝次序，被拒操作不留痕。
//
// 不变量：任何入口都是“先把事件结算到该时刻、再应用操作”，
// 因此任一时刻的保单状态、欠费金额与出险判定都能精确复现；
// 相同操作序列重放得到完全相同的状态轨迹、借款余额与赔付结论。
